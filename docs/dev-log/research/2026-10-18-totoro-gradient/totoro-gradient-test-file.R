args <- commandArgs(TRUE)
.libPaths(unique(c(args[1], path.expand('~/R/lib'), .libPaths())))
library(gllvmTMB)
library(testthat)
options(gllvmTMB.quiet_grammar_notes = TRUE)
res <- withr::with_envvar(c(NOT_CRAN = 'true'), test_file(args[2], reporter = 'summary', stop_on_failure = FALSE))
d <- as.data.frame(res)
tally <- list(failed = sum(d$failed), errors = sum(d$error), warnings = sum(d$warning), skipped = sum(d$skipped), passed = sum(d$passed))
print(tally)
jsonlite::write_json(tally, args[3], auto_unbox = TRUE, pretty = TRUE)
saveRDS(res, sub('json$', 'rds', args[3]))
quit(status = as.integer(tally$failed > 0 || tally$errors > 0))
